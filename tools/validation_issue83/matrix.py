"""Declared bounded support matrix for issue #83.

This module only *declares* rows. It states which option combinations the
validation attempts and which products each combination must produce. It does
not decide numerical acceptance: schedule equality is delegated verbatim to
``tools/compare_motioncorr.py --gate exact`` and motion truth to
``tools/run_known_motion_gates.py``. Those definitions are not redefined here.

Two axes are kept apart on purpose (issue #83 pass criteria):

* ``implementation`` coverage -- the option runs natively on CUDA, produces the
  complete declared product set with readable headers and metadata, and repeats
  / batches / resumes to identical pixels and metadata.
* ``numerical`` gates -- motion truth and CPU-agreement diagnostics. Those are
  reported by the existing tools under their own verdicts and are never implied
  by an implementation row passing.

EER and compressed decoding paths are deliberately absent: they remain issue #8.
"""

