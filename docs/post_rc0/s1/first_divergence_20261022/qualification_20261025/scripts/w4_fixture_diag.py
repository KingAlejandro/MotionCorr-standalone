# Frozen before any cpu64 diagnostic output exists. Both limits are pre-existing: the
# reviewed (2,1) oracle's G-R limits (field vs closed form 1e-12 px; render vs stored 1e-5).
LIM_FIELD_PX = 1e-12
LIM_RENDER = 1e-5
sha = lambda b: hashlib.sha256(b).hexdigest()
res = dict(protocol="w4-loaded-fixture/v2", control="D fixture identity", state="RUNNING",
           python=sys.version.split()[0], numpy=np.__version__, platform=platform.platform(),
           machine=platform.machine(), limits=dict(field_px=LIM_FIELD_PX, render=LIM_RENDER))


def npy_parts(raw):
    f = io.BytesIO(raw)
    ver = np.lib.format.read_magic(f)
    hdr = (np.lib.format.read_array_header_1_0 if ver == (1, 0) else np.lib.format.read_array_header_2_0)(f)
    off = f.tell()
    return dict(version=list(ver), header_dict=dict(descr=np.dtype(hdr[2]).str, fortran_order=hdr[1], shape=list(hdr[0])),
                header_len=off), raw[:off], raw[off:]


def ordered(a):
    i = a.view("<i8" if a.dtype.itemsize == 8 else "<i4").astype(np.int64)
    lo = np.int64(-(2 ** 63)) if a.dtype.itemsize == 8 else np.int64(-(2 ** 31))
    return np.where(i < 0, lo - i, i)


def diff(a, b):
    a = np.ascontiguousarray(a); b = np.ascontiguousarray(b)
    if a.shape != b.shape or a.dtype != b.dtype:
        return dict(comparable=False, shapes=[list(a.shape), list(b.shape)], dtypes=[a.dtype.str, b.dtype.str])
    neq = a.view(np.uint8).reshape(a.size, -1) != b.view(np.uint8).reshape(b.size, -1)
    n = int(neq.any(axis=1).sum())
    d = np.abs(a.astype(np.float64) - b.astype(np.float64))
    u = np.abs(ordered(a) - ordered(b))
    out = dict(comparable=True, elements=int(a.size), differing_elements=n, max_abs=float(d.max()),
               max_ulp=int(u.max()), ulp_histogram={str(k): int((u == k).sum()) for k in (1, 2, 3, 4)})
    out["ulp_histogram"][">4"] = int((u > 4).sum())
    if n:
        idx = np.unravel_index(int(np.argmax(d)), a.shape)
        out["argmax_index"] = [int(i) for i in idx]
    return out


def save_bytes(arr):
    buf = io.BytesIO(); np.save(buf, arr, allow_pickle=False); return buf.getvalue()


try:
    try:
        res["numpy_config"] = np.show_config(mode="dicts")
    except Exception as e:  # NumPy < 1.25 has no mode=; config is context, not a check
        res["numpy_config"] = f"unavailable: {type(e).__name__}"
    raw = {k: (FIX / k).read_bytes() for k in PINS}
    res["pinned_inputs"] = {k: sha(v) for k, v in raw.items()}
    src = {k: sha((SRC / k).read_bytes()) for k in SRC_PINS}
    res["sources"] = src
    bad = [k for k in PINS if res["pinned_inputs"][k] != PINS[k]] + [k for k in SRC_PINS if src[k] != SRC_PINS[k]]
    man = json.loads(raw["MANIFEST.json"])
    res["manifest_numpy"] = man.get("numpy")
    bad += [f"MANIFEST:{k}" for k in ("affine_field.npy", "affine_target.npy", "affine.mrcs")
            if man["cases"]["affine"]["files"][k] != PINS[k]]
    if bad:
        res["state"] = "INPUT_PIN_MISMATCH"; res["mismatch"] = bad
        raise SystemExit(2)

    import generate_motion_diagnostics as gen  # noqa: E402
    from motion_field import read_mrc  # noqa: E402
    r = gen.recipe("affine")
    movie, target, truth = gen.render(r)
    pinned_movie, _ = read_mrc(FIX / "affine.mrcs")
    arrays = {}
    for name, regen in (("affine_field.npy", truth), ("affine_target.npy", target)):
        meta_p, hdr_p, pay_p = npy_parts(raw[name])
        pinned = np.load(io.BytesIO(raw[name]), allow_pickle=False)
        # S: does this NumPy serialize the pinned array to the pinned bytes? (header format test)
        resaved = save_bytes(pinned)
        meta_s, hdr_s, pay_s = npy_parts(resaved)
        # R: regenerated array serialized by this NumPy, compared part by part
        regen_b = save_bytes(regen)
        meta_r, hdr_r, pay_r = npy_parts(regen_b)
        arrays[name] = dict(
            pinned_header=meta_p, pinned_header_bytes_sha256=sha(hdr_p), pinned_payload_sha256=sha(pay_p),
            resave_of_pinned_identical=resaved == raw[name], resave_header_identical=hdr_s == hdr_p,
            resave_payload_identical=pay_s == pay_p,
            regenerated_sha256=sha(regen_b), regenerated_header=meta_r,
            regenerated_header_identical=hdr_r == hdr_p, regenerated_payload_identical=pay_r == pay_p,
            regenerated_dtype=regen.dtype.str, payload_diff=diff(regen, pinned))
        arrays[name]["_pinned"] = pinned
    arrays["affine.mrcs (data only)"] = dict(payload_diff=diff(movie.astype("<f4"), pinned_movie.astype("<f4")))
    res["arrays"] = {k: {kk: vv for kk, vv in v.items() if kk != "_pinned"} for k, v in arrays.items()}

    # L: localisation (report-only). Field: generator matmul path versus an elementwise
    # closed form with the same operand order. Target: NumPy vectorized cos/exp versus
    # scalar libm (math) with the generator's operand order.
    pf = arrays["affine_field.npy"]["_pinned"]
    q = gen.grid(r); c = np.array([r["nx"], r["ny"]]) / 2
    ew = []
    for f in range(r["frames"]):
        g, a = gen.transform(r, f)
        d0, d1 = q[..., 0] - c[0], q[..., 1] - c[1]
        fwd = np.stack((q[..., 0] + g[0] + (d0 * a[0, 0] + d1 * a[0, 1]),
                        q[..., 1] + g[1] + (d0 * a[1, 0] + d1 * a[1, 1])), axis=-1)
        ew.append(q - fwd)
    ew = np.stack(ew)
    pt = arrays["affine_target.npy"]["_pinned"]
    nx, ny = r["nx"], r["ny"]
    lt = np.empty((ny, nx), "<f4")
    for y in range(ny):
        for x in range(nx):
            s = 0.0
            for kx, ky, amp, ph in [(3, 2, 1., .2), (7, -3, .7, 1.1), (11, 5, .5, -.4), (19, -13, .25, .7)]:
                s += amp * math.cos(2 * math.pi * (kx * float(x) / nx + ky * float(y) / ny) + ph)
            for cx, cy, amp, w in [(31, 23, 3., 3.), (82, 57, -2., 5.), (103, 34, 2., 4.)]:
                dx, dy = float(x) - cx, float(y) - cy   # NumPy's array **2 is an exact square
                s += amp * math.exp(-(dx * dx + dy * dy) / (2 * w ** 2))
            lt[y, x] = np.float32(r["pedestal"] + r["contrast"] * s)
    res["localisation_report_only"] = dict(
        field_elementwise_vs_pinned=diff(ew, pf), field_elementwise_vs_regenerated=diff(ew, truth),
        target_scalar_libm_vs_pinned=diff(lt, pt), target_scalar_libm_vs_regenerated=diff(lt, target))

    # Classification (frozen). Adoption of the loaded pinned arrays requires payload
    # differences within the pre-existing limits; header class is descriptive.
    F = res["arrays"]["affine_field.npy"]; T = res["arrays"]["affine_target.npy"]
    M = res["arrays"]["affine.mrcs (data only)"]
    hdr_differs = not (F["resave_header_identical"] and F["regenerated_header_identical"]
                       and T["resave_header_identical"] and T["regenerated_header_identical"])
    pay_differs = not (F["regenerated_payload_identical"] and T["regenerated_payload_identical"]
                       and M["payload_diff"]["differing_elements"] == 0)
    within = (F["payload_diff"].get("comparable") and T["payload_diff"].get("comparable") and M["payload_diff"].get("comparable")
              and F["payload_diff"]["max_abs"] <= LIM_FIELD_PX and T["payload_diff"]["max_abs"] <= LIM_RENDER
              and M["payload_diff"]["max_abs"] <= LIM_RENDER)
    if F["regenerated_sha256"] == PINS["affine_field.npy"]:
        cls = "NOT_REPRODUCED"          # contradicts the retained first FAIL: stop and investigate
    elif hdr_differs and not pay_differs:
        cls = "HEADER_FORMAT_ONLY"
    elif not hdr_differs and pay_differs:
        cls = "PAYLOAD_WITHIN_LIMITS" if within else "PAYLOAD_SEMANTIC"
    elif hdr_differs and pay_differs:
        cls = "HEADER_AND_PAYLOAD_WITHIN_LIMITS" if within else "HEADER_AND_PAYLOAD_SEMANTIC"
    else:
        cls = "UNEXPLAINED"             # bytes differ but neither part does: stop
    res["classification"] = cls
    res["adoptable"] = cls in ("HEADER_FORMAT_ONLY", "PAYLOAD_WITHIN_LIMITS", "HEADER_AND_PAYLOAD_WITHIN_LIMITS")
    res["state"] = "COMPLETE"
except SystemExit:
    raise
except Exception:
    res["state"] = "EXCEPTION"; res["traceback"] = traceback.format_exc()
    raise SystemExit(2)
finally:
    OUT.write_text(json.dumps(res, indent=1, allow_nan=False, default=str) + "\n")
    print(json.dumps({k: res.get(k) for k in ("state", "classification", "adoptable", "numpy", "manifest_numpy")}))
