#!/usr/bin/env python3
"""Regenerate the small review tables from retained scalar measurements (no NumPy)."""
import csv
import json
import math
from pathlib import Path
from statistics import median

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"
primary = json.loads((R / "primary-60.json").read_text())
fair = json.loads((R / "conditioned-cpu-60.json").read_text())
products = json.loads((R / "global-only-30.json").read_text())
assert len(primary) == len(fair) == 60 and len(products) == 30
assert len({(r["movie"], r["grid"]) for r in primary}) == 60
assert all(r["A0_identity_parent"] for r in primary)


def transitions(rows, a, b):
    cells = [0, 0, 0, 0]  # ++, +-, -+, --
    for row in rows:
        x, y = (row["arms"][k]["relative_rmse"] >= 0.1 for k in (a, b))
        cells[0 if x and y else 1 if x else 2 if y else 3] += 1
    n = cells[1] + cells[2]
    p = min(1, 2 * sum(math.comb(n, i) for i in range(min(cells[1:3]) + 1)) / 2**n)
    return cells, p


lines = ["# Retained measurement tables", "", "Generated by `python3 tools/summarize.py`.", "",
         "## Primary fixed CPU references", "",
         "| Family/grid | n | A0 | A1 | A2 | N1 | N2 |",
         "|---|---:|---:|---:|---:|---:|---:|"]
groups = {}
for fam in ("e10216", "e12963", "e10474f3"):
    for grid in (5, 3, None):
        group = [r for r in primary if r["movie"].startswith(fam + "-") and (grid is None or r["grid"] == grid)]
        groups[fam + (f"-p{grid}" if grid else "-both")] = group
for grid in (5, 3, None):
    groups["pooled" + (f"-p{grid}" if grid else "-both")] = [r for r in primary if grid is None or r["grid"] == grid]
for name, rows in groups.items():
    counts = [sum(r["arms"][a]["relative_rmse"] >= .1 for r in rows) for a in ("A0", "A1", "A2", "N1", "N2")]
    lines.append("| " + " | ".join(map(str, [name, len(rows), *counts])) + " |")
lines += ["", "Cells below are (++,+−,−+,−−), with the left arm first. Exact two-sided McNemar p; no multiplicity adjustment.", "",
          "| Family/grid | Contrast | Cells | p |", "|---|---|---|---:|"]
for name, rows in groups.items():
    for a, b in (("A0", "A1"), ("N1", "A1"), ("N2", "A1"), ("A1", "A2")):
        cells, p = transitions(rows, a, b)
        lines.append(f"| {name} | {a}→{b} | {tuple(cells)} | {p:.10g} |")

lines += ["", "## Global trajectory error", "",
          "Original CPU STARs; per-config two-dimensional max/RMS over frames. The two e10216-01 configurations are separated below, and remain in every census and CSV.", "",
          "| Arm | Median max, other 58 (px) | Worst max, other 58 (px) | Median RMS, other 58 (px) | e10216-01 max/RMS (px) |",
          "|---|---:|---:|---:|---|"]
for arm in ("A0", "A1", "A2"):
    q = [r["arms"][arm] for r in primary if r["movie"] != "e10216-01"]
    bad = next(r["arms"][arm] for r in primary if r["movie"] == "e10216-01")
    lines.append(f'| {arm} | {median(x["global_max_px"] for x in q):.10g} | {max(x["global_max_px"] for x in q):.10g} | {median(x["global_rms_px"] for x in q):.10g} | {bad["global_max_px"]:.10g} / {bad["global_rms_px"]:.10g} |')

lines += ["", "## Global-only products (30 movies)", "", "| Arm | DW median relRMSE | non-DW median relRMSE |", "|---|---:|---:|"]
for a in ("A0", "A1"):
    vals = [median(r["arms"][a][k]["relative_rmse"] for r in products) for k in ("DW", "nonDW")]
    lines.append(f"| {a} | {vals[0]:.12g} | {vals[1]:.12g} |")

witnesses = json.loads((R / "residual-witnesses.json").read_text())
assert len(witnesses) == sum(sum(r["arms"][a]["relative_rmse"] >= .1 for a in ("A1", "A2")) for r in primary)
lines += ["", "## Residual fixed-reference positive witnesses", "",
          "First material accepted-patch witness uses #255's >0.5 px candidate-separation convention, preferring its S1-relevant patch screen (acceptance flip or >1 px final trajectory difference). This is not the first floating-point inequality. The JSON retains scope, samples and map provenance.", "",
          "| Configuration/arm | Kind | Patch; iteration; frame | CPU / CUDA peak margin (CPU-baseline ULPs / own ULPs) |",
          "|---|---|---|---|"]
for r in witnesses:
    detail = f'{r["patch"]}; {r["iteration"]}; {r["frame"]}' if "patch" in r else "—"
    margin = f'{r["cpu_margin_ulps"]:.6g} / {r["cuda_margin_ulps"]:.6g}' if "cpu_margin_ulps" in r else "—"
    lines.append(f'| {r["case"]} | {r.get("subclassification", r["kind"])} | {detail} | {margin} |')
(R / "tables.md").write_text("\n".join(lines) + "\n")

with (R / "per-config.csv").open("w") as f:
    w = csv.writer(f, lineterminator="\n")
    w.writerow(["movie", "grid", "regenerated_reference", *[f"{a}_{k}" for a in ("A0", "A1", "A2", "N1", "N2") for k in ("relative_rmse", "global_max_px", "global_rms_px", "S1_positive")]])
    for r in primary:
        w.writerow([r["movie"], r["grid"], r["reference_regenerated"], *[v for a in ("A0", "A1", "A2", "N1", "N2") for v in (r["arms"][a]["relative_rmse"], r["arms"][a]["global_max_px"], r["arms"][a]["global_rms_px"], r["arms"][a]["relative_rmse"] >= .1)]])
assert [sum(r["arms"][a]["relative_rmse"] >= .1 for r in primary) for a in ("A0", "A1", "A2", "N1", "N2")] == [17, 19, 16, 21, 15]
assert sum(r["arms"]["A2"]["relative_rmse"] >= .1 for r in fair) == 0
print("60 primary + 60 conditioned-reference configs; 30 global products; 35 residual witnesses; summaries regenerated")
