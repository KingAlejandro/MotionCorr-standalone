#!/usr/bin/env python3
"""
Standalone Benchmark Scaling & Speedup Plotter
Decoupled plotting script generated by MotionCorr Visualization Agent.
"""

import argparse
import json
import math
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple


def parse_benchmark_json(json_path: Path) -> List[Dict]:
    with open(json_path, "r", encoding="utf-8") as f:
        data = json.load(f)
    return data.get("cases", [])


def compute_scaling_metrics(cases: List[Dict]) -> Tuple[List[int], List[float], List[float], List[float]]:
    # Sort cases by thread count
    sorted_cases = sorted(cases, key=lambda c: c.get("threads", 1))
    threads = [c.get("threads", 1) for c in sorted_cases]
    wall_times = [c.get("mean_wall_time_sec", 0.0) for c in sorted_cases]
    
    t1 = wall_times[0] if wall_times and wall_times[0] > 0 else 1.0
    speedups = [t1 / max(1e-6, t) for t in wall_times]
    efficiencies = [(s / max(1, p)) * 100.0 for s, p in zip(speedups, threads)]
    return threads, wall_times, speedups, efficiencies


def plot_with_matplotlib(
    title: str,
    threads: List[int],
    wall_times: List[float],
    speedups: List[float],
    out_png: Path
) -> bool:
    try:
        import matplotlib.pyplot as plt
        import matplotlib
        matplotlib.use("Agg")
    except ImportError:
        return False

    fig, ax1 = plt.subplots(figsize=(9, 5), dpi=150)
    color_time = "#dc2626"
    color_sp = "#1d4ed8"

    ax1.set_xlabel("OpenMP Thread Count", fontsize=11, fontweight="bold")
    ax1.set_ylabel("Execution Time (s)", color=color_time, fontsize=11, fontweight="bold")
    ax1.plot(threads, wall_times, color=color_time, marker="o", linewidth=2.5, label="Wall-Clock Time")
    ax1.tick_params(axis="y", labelcolor=color_time)
    ax1.set_xticks(threads)
    ax1.grid(True, linestyle="--", alpha=0.5)

    ax2 = ax1.twinx()
    ax2.set_ylabel("Speedup Multiplier (x)", color=color_sp, fontsize=11, fontweight="bold")
    ax2.plot(threads, speedups, color=color_sp, marker="s", linewidth=2.5, label="Measured Speedup")
    # Linear ideal
    ax2.plot([min(threads), max(threads)], [min(threads), max(threads)], color="#94a3b8", linestyle="--", label="Ideal Linear")
    ax2.tick_params(axis="y", labelcolor=color_sp)

    plt.title(title, fontsize=13, fontweight="bold", pad=15)
    fig.tight_layout()
    out_png.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(out_png, bbox_inches="tight")
    plt.close()
    return True


def plot_with_svg(
    title: str,
    threads: List[int],
    wall_times: List[float],
    speedups: List[float],
    out_svg: Path
) -> None:
    width, height = 850, 500
    margin_l, margin_r, margin_t, margin_b = 80, 80, 60, 60
    plot_w = width - margin_l - margin_r
    plot_h = height - margin_t - margin_b

    max_threads = max(threads) if threads else 10
    max_time = max(wall_times) * 1.1 if wall_times else 100.0
    max_sp = max(max(speedups) if speedups else 1.0, max_threads) * 1.1

    def x_c(th): return margin_l + (th / max_threads) * plot_w
    def y_t(t): return margin_t + plot_h - (t / max_time) * plot_h
    def y_s(s): return margin_t + plot_h - (s / max_sp) * plot_h

    lines = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" width="{width}" height="{height}">',
        f'  <rect width="{width}" height="{height}" fill="#ffffff" rx="8"/>',
        f'  <text x="{width / 2}" y="32" font-family="sans-serif" font-size="16" font-weight="bold" fill="#0f172a" text-anchor="middle">{title}</text>',
        f'  <rect x="{margin_l}" y="{margin_t}" width="{plot_w}" height="{plot_h}" fill="#f8fafc" stroke="#e2e8f0"/>',
    ]

    # Grid
    for i in range(6):
        t_val = (max_time / 5) * i
        y = y_t(t_val)
        lines.append(f'  <line x1="{margin_l}" y1="{y:.1f}" x2="{margin_l + plot_w}" y2="{y:.1f}" stroke="#e2e8f0"/>')
        lines.append(f'  <text x="{margin_l - 10}" y="{y + 4:.1f}" font-family="sans-serif" font-size="10" fill="#64748b" text-anchor="end">{t_val:.1f}s</text>')
        s_val = (max_sp / 5) * i
        y_sp = y_s(s_val)
        lines.append(f'  <text x="{margin_l + plot_w + 10}" y="{y_sp + 4:.1f}" font-family="sans-serif" font-size="10" fill="#1d4ed8" text-anchor="start">{s_val:.1f}x</text>')

    for th in threads:
        x = x_c(th)
        lines.append(f'  <line x1="{x:.1f}" y1="{margin_t + plot_h}" x2="{x:.1f}" y2="{margin_t + plot_h + 5}" stroke="#64748b"/>')
        lines.append(f'  <text x="{x:.1f}" y="{margin_t + plot_h + 20}" font-family="sans-serif" font-size="11" fill="#334155" text-anchor="middle">{th} th</text>')

    # Ideal linear
    lines.append(f'  <line x1="{x_c(1):.1f}" y1="{y_s(1):.1f}" x2="{x_c(max_threads):.1f}" y2="{y_s(max_threads):.1f}" stroke="#94a3b8" stroke-dasharray="4,4" stroke-width="1.5"/>')

    # Polyline speedup
    pts_sp = " ".join(f"{x_c(th):.1f},{y_s(s):.1f}" for th, s in zip(threads, speedups))
    lines.append(f'  <polyline points="{pts_sp}" fill="none" stroke="#1d4ed8" stroke-width="2.5"/>')
    for th, s in zip(threads, speedups):
        lines.append(f'  <circle cx="{x_c(th):.1f}" cy="{y_s(s):.1f}" r="4.5" fill="#1d4ed8" stroke="#ffffff" stroke-width="1.5"/>')

    # Polyline wall time
    pts_wt = " ".join(f"{x_c(th):.1f},{y_t(t):.1f}" for th, t in zip(threads, wall_times))
    lines.append(f'  <polyline points="{pts_wt}" fill="none" stroke="#dc2626" stroke-width="2.5"/>')
    for th, t in zip(threads, wall_times):
        lines.append(f'  <circle cx="{x_c(th):.1f}" cy="{y_t(t):.1f}" r="4.5" fill="#dc2626" stroke="#ffffff" stroke-width="1.5"/>')

    # Labels
    lines.append(f'  <text x="{margin_l + plot_w / 2}" y="{height - 15}" font-family="sans-serif" font-size="12" font-weight="600" text-anchor="middle">OpenMP Thread Count</text>')
    lines.append(f'  <text x="25" y="{margin_t + plot_h / 2}" font-family="sans-serif" font-size="12" font-weight="600" text-anchor="middle" transform="rotate(-90 25 {margin_t + plot_h / 2})">Execution Time (s)</text>')
    lines.append(f'  <text x="{width - 20}" y="{margin_t + plot_h / 2}" font-family="sans-serif" font-size="12" font-weight="600" fill="#1d4ed8" text-anchor="middle" transform="rotate(90 {width - 20} {margin_t + plot_h / 2})">Speedup Multiplier (x)</text>')

    lines.append('</svg>')
    out_svg.parent.mkdir(parents=True, exist_ok=True)
    with open(out_svg, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def main():
    parser = argparse.ArgumentParser(description="Standalone Benchmark Scaling Plotter")
    parser.add_argument("--input", required=True, type=Path, help="Path to benchmark JSON summary")
    parser.add_argument("--out-dir", type=Path, default=Path("plots"), help="Output directory for plots")
    parser.add_argument("--title", type=str, default="MotionCorr Telemetry (Scaling)", help="Plot title")
    parser.add_argument("--format", nargs="+", default=["svg", "png"], choices=["svg", "png", "all"], help="Output formats")
    args = parser.parse_args()

    if not args.input.exists():
        print(f"Error: input file {args.input} does not exist.", file=sys.stderr)
        sys.exit(1)

    cases = parse_benchmark_json(args.input)
    if not cases:
        print(f"Error: no benchmark cases found in {args.input}", file=sys.stderr)
        sys.exit(1)

    threads, wall_times, speedups, efficiencies = compute_scaling_metrics(cases)
    print(f"[Scaling Plotter] Extracted {len(threads)} data points: {threads} threads")

    args.out_dir.mkdir(parents=True, exist_ok=True)
    stem = args.input.stem

    if "svg" in args.format or "all" in args.format:
        svg_path = args.out_dir / f"{stem}_scaling.svg"
        plot_with_svg(args.title, threads, wall_times, speedups, svg_path)
        print(f"[Scaling Plotter] Generated SVG: {svg_path}")

    if "png" in args.format or "all" in args.format:
        png_path = args.out_dir / f"{stem}_scaling.png"
        if plot_with_matplotlib(args.title, threads, wall_times, speedups, png_path):
            print(f"[Scaling Plotter] Generated PNG: {png_path}")
        else:
            print("[Scaling Plotter] Matplotlib unavailable; SVG was generated as primary artifact.")


if __name__ == "__main__":
    main()
