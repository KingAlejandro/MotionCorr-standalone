@dataclass(frozen=True)
class Row:
    """One declared configuration of the support matrix."""

    row_id: str
    fixture: str
    #: Free-form axis labels, used only to group the published table.
    axes: Dict[str, str]
    #: Options appended to the common invocation, verbatim.
    args: List[str]
    #: Suffixes of the per-movie products this configuration must produce.
    #: ``""`` is the corrected average itself, ``.star`` the movie metadata.
    products: List[str] = field(default_factory=lambda: [".mrc", ".star"])
    #: Schedules compared against the uninterrupted run for exact equality.
    schedules: List[str] = field(default_factory=lambda: ["repeat", "batch", "resume"])
    #: Number of movies in the generated dataset for this row.
    n_movies: int = 3
    #: Set when the row is expected to fail the option validator instead of running.
    expect_reject: Optional[str] = None
    notes: str = ""


