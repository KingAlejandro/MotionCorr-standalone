#!/usr/bin/env python3
"""Tables T1-T8 of ../ANALYSIS-PLAN.md from w7.json. Usage: summarize_w7.py w7.json tables.md per_movie.csv"""
import csv
import json
import sys
import numpy as np

src, md_out, csv_out = sys.argv[1:4]
D = json.load(open(src))
M = D['movies']
assert D['gates']['pass']
CONDS = ['dose05', 'dose1', 'dose2', 'dose4', 'pedestal0', 'contrast025', 'contrast4', 'nonsquare', 'outmodel', 'pedestal32']
INMODEL = CONDS[:8]
COMPS = ['repr', 'glob_const', 'glob_var', 'obs_const', 'obs_var']
LIM = dict(rms=.20, p95=.40, max=.80)
by = {c: sorted([m for m in M if m['condition'] == c], key=lambda m: m['seed']) for c in CONDS}
med = lambda a: float(np.median(a))
f3 = lambda v: f'{v:.3f}'
rng = lambda a: f'{med(a):.3f} [{min(a):.3f}, {max(a):.3f}]'
L = []
w = L.append

w('# W7 tables (generated by scripts/summarize_w7.py from results/w7.json)\n')
g = D['gates']
w(f"Gates: G1 {g['G1']}, G2 {g['G2']}, G3 max {g['G3_max_px']:.2e} px, G4 max {g['G4_max_px']:.2e} px, G5 max {g['G5_max_px']:.2e} px over {g['n']} movies. NumPy {D['numpy']}.\n")
w('All values are F (flags-off) arm, unchanged evaluator, Å unless marked px. "median [min, max]" is over the 10 seeds of a condition.\n')

w('## T1 pass/fail (failing limits per movie: R = RMS > 0.20, P = p95 > 0.40, M = max > 0.80)\n')
w('| condition | ' + ' | '.join(f's{s:02d}' for s in range(10)) + ' | pass | RMS fail | p95 fail | max fail |')
w('|---|' + '---|'*14)
for c in CONDS:
    cells = ['pass' if m['pass'] else ''.join({'rms': 'R', 'p95': 'P', 'max': 'M'}[k] for k in m['fails']) for m in by[c]]
    w(f'| {c} | ' + ' | '.join(cells) + f" | {sum(m['pass'] for m in by[c])} | " + ' | '.join(str(sum(k in m['fails'] for m in by[c])) for k in LIM) + ' |')
w(f"\nTotal: {sum(m['pass'] for m in M)} of 100 meet all three limits; RMS fails in {sum('rms' in m['fails'] for m in M)}, p95 in {sum('p95' in m['fails'] for m in M)}, max in {sum('max' in m['fails'] for m in M)}. `dose1`, `pedestal0`, `contrast025` and `contrast4` share each seed's Poisson draws.\n")

w('## T2 rigid (per-frame spatial mean) vs local residual\n')
w('| condition | field RMS | rigid share of MS | rigid RMS / p95 / max | local RMS / p95 / max |')
w('|---|---|---|---|---|')
for c in CONDS:
    ms = by[c]
    w(f"| {c} | {rng([m['field_A']['rms'] for m in ms])} | {rng([m['T2']['ms_share_rigid'] for m in ms])} | "
      + ' / '.join(f3(med([m['T2']['rigid_A'][q] for m in ms])) for q in LIM) + ' | '
      + ' / '.join(f3(med([m['T2']['local_A'][q] for m in ms])) for q in LIM) + ' |')

w('\n## T3 temporal structure (median per-frame-bin RMS, Å)\n')
bins = list(M[0]['T3']['bins_rms_A'])
for c in ['dose1', 'dose4', 'outmodel', 'pedestal32']:
    ms = by[c]
    w(f'\n**{c}**\n')
    w('| frames | field | rigid | local | ' + ' | '.join(COMPS) + ' |')
    w('|---|' + '---|'*(3+len(COMPS)))
    for b in bins:
        w(f'| {b} | ' + ' | '.join(f3(med([m['T3']['bins_rms_A'][b][k] for m in ms])) for k in ['e', 'rigid', 'local']+COMPS) + ' |')
w('\nFrame holding the max, per condition (seeds s00..s09):\n')
for c in CONDS:
    w(f"- {c}: {[m['T3']['max_frame'] for m in by[c]]}")
w('\nGlobal trajectory error `eps_g = global - g` over frames 1-39 (RMS, Å): time-constant part (includes the frame-0 anchor), cubic part of the remainder, jitter.\n')
w('| condition | total | time-constant | cubic | jitter |')
w('|---|---|---|---|---|')
for c in CONDS:
    ms = by[c]
    w(f'| {c} | ' + ' | '.join(f3(med([m['T3']['eps_g_A'][k] for m in ms])) for k in ['total', 'const', 'cubic', 'jitter']) + ' |')

w('\n## T4 spatial structure (regions by the patch-centre hull)\n')
w('| condition | point fraction int / edge / corner | field RMS int / edge / corner | share of points above p95 int / edge / corner | max in corner / edge / int |')
w('|---|---|---|---|---|')
for c in CONDS:
    ms = by[c]; R = ['interior', 'edge', 'corner']
    w(f'| {c} | ' + ' / '.join(f3(ms[0]['T4']['fraction'][k]) for k in R) + ' | '
      + ' / '.join(f3(med([m['T4']['rms_A'][k]['e'] for m in ms])) for k in R) + ' | '
      + ' / '.join(f3(med([m['T4']['above_p95_share'][k] for m in ms])) for k in R) + ' | '
      + ' / '.join(str(sum(m['T4']['max_region'] == k for m in ms)) for k in ['corner', 'edge', 'interior']) + ' |')
w('\nPer-region RMS of the dominant component `obs_const` (median, Å):\n')
w('| condition | interior | edge | corner |')
w('|---|---|---|---|')
for c in INMODEL + ['outmodel']:
    w(f'| {c} | ' + ' | '.join(f3(med([m['T4']['rms_A'][k]['obs_const'] for m in by[c]])) for k in ['interior', 'edge', 'corner']) + ' |')

w('\n## T5 representability (reported separately; never subtracted from any error)\n')
w('Both depend only on the motion model and geometry; the table checks they are identical across the 10 seeds of a condition.\n')
w('| condition | R-lat RMS / p95 / max | R-pipe RMS / p95 / max | R-pipe (patch-mean truth) RMS / p95 / max | identical over seeds | centre vs patch-mean truth px RMS / max | fwd-inv gap px RMS / max |')
w('|---|---|---|---|---|---|---|')
for c in CONDS:
    ms = by[c]; t = ms[0]['T5']
    same = all(m['T5']['R_lat_A'] == t['R_lat_A'] and m['T5']['R_pipe_A'] == t['R_pipe_A'] for m in ms)
    fm = lambda d: ' / '.join(f'{d[q]:.4f}' for q in LIM)
    w(f"| {c} | {fm(t['R_lat_A'])} | {fm(t['R_pipe_A'])} | {fm(t['R_pipe_patchmean_A'])} | {same} | "
      f"{t['centre_vs_patchmean_px']['rms']:.4f} / {t['centre_vs_patchmean_px']['max']:.4f} | {t['fwd_inv_gap_px']['rms']:.4f} / {t['fwd_inv_gap_px']['max']:.4f} |")

w('\n## T6 observation vs fit: exact split `e = repr + glob_const + glob_var + obs_const + obs_var`\n')
w('Mean-square shares (median over seeds; cross terms listed so that shares + cross = 1 per movie):\n')
w('| condition | ' + ' | '.join(COMPS) + ' | sum of cross terms | largest cross term |')
w('|---|' + '---|'*(len(COMPS)+2))
for c in CONDS:
    ms = by[c]; b = [m['T6']['budget'] for m in ms]
    cr = {k: med([x['cross'][k] for x in b]) for k in b[0]['cross']}
    big = max(cr, key=lambda k: abs(cr[k]))
    w(f'| {c} | ' + ' | '.join(f3(med([x['share'][k] for x in b])) for k in COMPS) + f" | {f3(med([sum(x['cross'].values()) for x in b]))} | {big} {f3(cr[big])} |")
w('\nAblation (counterfactual for attribution, not an achievable result): field RMS / p95 / max with one component removed (median).\n')
w('| condition | actual | -repr | -glob (both) | -obs_const | -obs_var | -obs (both) | -glob-obs (= R-pipe residual) |')
w('|---|---|---|---|---|---|---|---|')
for c in CONDS:
    ms = by[c]
    t = lambda key: ' / '.join(f3(med([m['T6']['ablation_A'][key][q] for m in ms])) for q in LIM)
    w(f"| {c} | " + ' / '.join(f3(med([m['field_A'][q] for m in ms])) for q in LIM) + ' | '
      + ' | '.join(t(k) for k in ['repr', 'glob', 'obs_const', 'obs_var', 'obs', 'glob+obs']) + ' |')
w('\nObservation error (px, median): `delta` = STAR observation - ideal observation for the actual global; the anchor test is amendment 2 (post hoc).\n')
w('| condition | RMS obs* | RMS delta | per-patch const | time-varying | anchor: mean RMS / scatter RMS / ratio | gain slope x / y | delta RMS by patch iterations (n) |')
w('|---|---|---|---|---|---|---|---|')
for c in CONDS[:-1]:
    o = [m['T6']['obs'] for m in by[c]]; a = [m['T6']['anchor'] for m in by[c]]
    it = {k: (med([x['delta_rms_px_by_iterations'][k] for x in o if k in x['delta_rms_px_by_iterations']]), sum(x['n_by_iterations'].get(k, 0) for x in o)) for k in sorted({k for x in o for k in x['n_by_iterations']})}
    w(f"| {c} | {f3(med([x['obs_star_rms_px'] for x in o]))} | {f3(med([x['delta_rms_px'] for x in o]))} | {f3(med([x['delta_const_rms_px'] for x in o]))} | {f3(med([x['delta_var_rms_px'] for x in o]))} | "
      f"{f3(med([x['mean_rms_px'] for x in a]))} / {f3(med([x['scatter_rms_px'] for x in a]))} / {rng([x['ratio'] for x in a])} | "
      f"{f3(med([x['gain_slope_xy'][0] for x in o]))} / {f3(med([x['gain_slope_xy'][1] for x in o]))} | "
      + ', '.join(f'{k} it: {v[0]:.3f} ({v[1]})' for k, v in it.items()) + ' |')
w('\n`pedestal32` (F) keeps no patches, so it has no local model and no observations: `e = (g - T) + eps_g`.\n')

w('## T7 dose scaling (median RMS over seeds; slope of log RMS on log dose over 0.5 / 1 / 2 / 4)\n')
doses = [('dose05', .5), ('dose1', 1.), ('dose2', 2.), ('dose4', 4.)]
rows = [('field (Å)', lambda m: m['field_A']['rms'])] + [(f'{k} (Å)', (lambda k: lambda m: m['T6']['components_A'][k]['rms'])(k)) for k in COMPS[1:]] + \
       [('delta per-patch const (px)', lambda m: m['T6']['obs']['delta_const_rms_px']), ('delta time-varying (px)', lambda m: m['T6']['obs']['delta_var_rms_px'])]
w('| quantity | dose 0.5 | 1 | 2 | 4 | log-log slope |')
w('|---|---|---|---|---|---|')
for name, fn in rows:
    v = [med([fn(m) for m in by[c]]) for c, _ in doses]
    s = np.polyfit(np.log([d for _, d in doses]), np.log(v), 1)[0]
    w(f'| {name} | ' + ' | '.join(f3(x) for x in v) + f' | {s:.2f} |')

w('\n## T8 ranking per condition\n')
w('Ranked by mean-square share (RMS limit) and by the ablation change of p95 and max. "Rescued" counts failing movies that would meet that limit with only that component removed (counterfactual).\n')
w('| condition | rank by MS share | rank by p95 ablation | rank by max ablation | failing movies | rescued by -obs_const (RMS / p95 / max) | rescued by -glob (RMS / p95 / max) |')
w('|---|---|---|---|---|---|---|')
for c in CONDS:
    ms = by[c]
    sh = {k: med([m['T6']['budget']['share'][k] for m in ms]) for k in COMPS}
    rk = lambda q: sorted(COMPS, key=lambda k: -med([m['field_A'][q]-m['T6']['ablation_A'][k][q] for m in ms]))
    fail = [m for m in ms if not m['pass']]
    resc = lambda key: ' / '.join(str(sum(q in m['fails'] and m['T6']['ablation_A'][key][q] <= LIM[q] for m in fail)) + '/' + str(sum(q in m['fails'] for m in fail)) for q in LIM)
    w(f"| {c} | {' > '.join(k for k in sorted(COMPS, key=lambda k: -sh[k])[:3])} | {' > '.join(rk('p95')[:3])} | {' > '.join(rk('max')[:3])} | {len(fail)} | {resc('obs_const')} | {resc('glob')} |")

open(md_out, 'w').write('\n'.join(L)+'\n')
with open(csv_out, 'w', newline='') as fh:
    cw = csv.writer(fh)
    cw.writerow(['movie', 'condition', 'seed', 'pass', 'fails', 'rms_A', 'p95_A', 'max_A', 'rigid_ms_share'] + [f'share_{k}' for k in COMPS] + ['share_cross']
                + [f'abl_{k}_{q}' for k in ['obs_const', 'glob'] for q in LIM] + ['R_lat_rms_A', 'R_pipe_rms_A', 'delta_const_px', 'delta_var_px', 'anchor_ratio', 'max_region', 'max_frame'])
    for c in CONDS:
        for m in by[c]:
            b = m['T6']['budget']; o = m['T6'].get('obs', {}); a = m['T6'].get('anchor', {})
            cw.writerow([m['movie'], c, m['seed'], m['pass'], '+'.join(m['fails']), *(f"{m['field_A'][q]:.5f}" for q in LIM), f"{m['T2']['ms_share_rigid']:.4f}"]
                        + [f"{b['share'][k]:.4f}" for k in COMPS] + [f"{sum(b['cross'].values()):.4f}"]
                        + [f"{m['T6']['ablation_A'][k][q]:.4f}" for k in ['obs_const', 'glob'] for q in LIM]
                        + [f"{m['T5']['R_lat_A']['rms']:.4f}", f"{m['T5']['R_pipe_A']['rms']:.4f}", f"{o.get('delta_const_rms_px', float('nan')):.4f}",
                           f"{o.get('delta_var_rms_px', float('nan')):.4f}", f"{a.get('ratio', float('nan')):.3f}", m['T4']['max_region'], m['T3']['max_frame']])
print('ok')
