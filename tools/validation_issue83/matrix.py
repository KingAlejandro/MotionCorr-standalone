def rows_by_id() -> Dict[str, Row]:
    return {r.row_id: r for r in ROWS}


def declared_axes() -> Dict[str, List[str]]:
    """Axis -> declared values, for the published support table."""
    axes: Dict[str, List[str]] = {}
    for row in ROWS:
        for axis, value in row.axes.items():
            axes.setdefault(axis, [])
            if value not in axes[axis]:
                axes[axis].append(value)
    return axes
